from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path

from app.models.schemas import SurgeryEvent
from app.repositories.base import JsonFileRepository


def _sortable_timestamp(ts: datetime) -> datetime:
    """Normalizes a timestamp for comparison. Python refuses to compare
    timezone-naive and timezone-aware datetimes (raises TypeError), and events
    can come from different sources -- seed data generated by a script vs.
    events appended live by EventService.add_event (which always uses
    datetime.now(timezone.utc)) -- so a naive timestamp slipping in from
    anywhere would otherwise crash every read of a surgery's history. Treat a
    naive timestamp as UTC rather than failing the whole history read."""
    return ts if ts.tzinfo is not None else ts.replace(tzinfo=timezone.utc)


class EventRepository(JsonFileRepository[SurgeryEvent]):
    """Append-only repository for surgery audit events. Historical events are
    never overwritten or deleted -- only new events are appended."""

    def __init__(self, data_dir: Path) -> None:
        super().__init__(data_dir / "surgery_events.json", SurgeryEvent, id_field="event_id")

    def find_by_surgery(self, surgery_id: str) -> list[SurgeryEvent]:
        events = [e for e in self.list_all() if e.surgery_id == surgery_id]
        return sorted(events, key=lambda e: _sortable_timestamp(e.timestamp))
